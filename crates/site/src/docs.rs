/// docs/reference/std-parts.md from std.parts: every std part, what its comment says, its parameters.
fn std_parts_page() -> String {
	let lines = partscript::lang::splitlines(partscript::project::STD);
	let mut out: Vec<String> = vec![
		"# Standard parts".into(),
		"".into(),
		"<!-- generated by the site tool (crates/site) from crates/partscript/src/std.parts: edit those comments, not this page -->".into(),
		"".into(),
		"Every project can `use` these: building blocks with their origin at the floor centre and their front toward -Y, like a prop. Their materials are parameters (pass `none` to leave a piece out).".into(),
		"".into(),
	];
	let mut k = 0;
	while k < lines.len() {
		let line = lines[k];
		if line.starts_with("def ") {
			let mut comment = Vec::new();
			let mut j = k;
			while j > 0 && lines[j - 1].starts_with('#') {
				comment.insert(0, lines[j - 1].trim_start_matches(['#', ' ']).trim_end().to_string());
				j -= 1;
			}
			let mut header = line.to_string();
			while header.trim_end().ends_with('\\') {
				k += 1;
				let trimmed = header.trim_end();
				header = format!("{} {}", &trimmed[..trimmed.len() - 1], lines[k].trim());
			}
			let words: Vec<&str> = header.split_whitespace().collect();
			let name = words[1];
			let params: Vec<&str> = words[2..].iter().copied().filter(|w| w.contains('=')).collect();
			out.extend([format!("## {name}"), "".into(), comment.join(" "), "".into(), "| parameter | default |".into(), "|---|---|".into()]);
			if params.is_empty() {
				out.push("| (none) | |".into());
			}
			for p in params {
				let (key, default) = p.split_once('=').unwrap();
				out.push(format!("| `{key}` | `{default}` |"));
			}
			out.extend(["".into(), "```parts".into(), format!("prop std_{name}_demo \"{name}\""), format!("  use {name}"), "```".into(), "".into()]);
		}
		k += 1;
	}
	out.join("\n")
}

/// docs/reference/materials.md from the default host's material library.
fn materials_page() -> String {
	use partscript::{BasicProvider, Recipe, TextureProvider};
	let host = partscript::Host::default();
	let library = BasicProvider::default().library();
	let mut out: Vec<String> = vec![
		"# Material library".into(),
		"".into(),
		"<!-- generated by the site tool (crates/site) from the default host (partscript::textures): do not edit -->".into(),
		"".into(),
		"Every project can name these by key (`mat=steel_dark`). A host can add its own; `partscript list` shows what yours knows.".into(),
		"".into(),
		"| key | finish | colour | notes |".into(),
		"|---|---|---|---|".into(),
	];
	let materials = host.materials.borrow();
	let mut keys: Vec<&String> = materials.keys().collect();
	keys.sort();
	for key in keys {
		let Some((_, _, Recipe::Surface { finish, hex })) = library.iter().find(|(k, _, _)| k == key) else { continue };
		let mat = &materials[key];
		let mut notes = Vec::new();
		if !mat.emission.is_empty() || mat.emission_strength > 0.0 {
			notes.push("lit (full bright)".to_string());
		}
		if mat.alpha < 1.0 {
			notes.push(format!("see-through ({})", kitlib::py::g(mat.alpha)));
		}
		out.push(format!("| `{key}` | {finish} | <span class=\"swatch\" style=\"background:#{hex}\"></span> `#{hex}` | {} |", notes.join(", ")));
	}
	let finishes: Vec<String> = partscript::lang::FINISHES.iter().map(|f| format!("`{f}`")).collect();
	out.extend([
		"".into(),
		"## Finishes".into(),
		"".into(),
		format!("Any colour is a material: `#rrggbb/finish`, where the finish is one of {} (paint when left off). `glow` is lit and full bright; `glass` is see-through.", finishes.join(", ")),
		"".into(),
	]);
	out.join("\n")
}

pub fn generated() -> [(&'static str, String); 2] {
	[("reference/std-parts.md", std_parts_page()), ("reference/materials.md", materials_page())]
}

