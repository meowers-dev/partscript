/// A heading's id as Python-Markdown's toc makes it: ascii, no punctuation, lower case, - between words.
fn slugify(text: &str) -> String {
	let kept: String = text.chars().filter(|c| c.is_ascii() && (c.is_ascii_alphanumeric() || *c == '_' || *c == '-' || c.is_ascii_whitespace())).collect();
	let lower = kept.trim().to_lowercase();
	let mut out = String::new();
	let mut gap = false;
	for c in lower.chars() {
		if c == '-' || c.is_ascii_whitespace() {
			gap = true;
		} else {
			if gap {
				out.push('-');
			}
			gap = false;
			out.push(c);
		}
	}
	if gap {
		out.push('-');
	}
	out
}

fn unique(id: String, ids: &mut HashSet<String>) -> String {
	let mut id = id;
	while id.is_empty() || ids.contains(&id) {
		id = match id.rsplit_once('_') {
			Some((head, n)) if !n.is_empty() && n.chars().all(|c| c.is_ascii_digit()) => format!("{head}_{}", n.parse::<u64>().unwrap() + 1),
			_ => format!("{id}_1"),
		};
	}
	ids.insert(id.clone());
	id
}

/// Markdown to HTML, every heading given an id; also [(id, title)] of its h2 sections.
fn markdown(text: &str) -> (String, Vec<(String, String)>) {
	let events: Vec<Event> = Parser::new_ext(text, Options::ENABLE_TABLES).collect();
	let mut ids = HashSet::new();
	let mut sections = Vec::new();
	let mut out: Vec<Event> = Vec::with_capacity(events.len());
	let mut k = 0;
	while k < events.len() {
		if let Event::Start(Tag::Heading { level, id: None, classes, attrs }) = &events[k] {
			let end = k + events[k..].iter().position(|e| matches!(e, Event::End(TagEnd::Heading(_)))).unwrap();
			let name: String = events[k + 1..end]
				.iter()
				.filter_map(|e| match e {
					Event::Text(t) | Event::Code(t) => Some(t.to_string()),
					_ => None,
				})
				.collect();
			let id = unique(slugify(&name), &mut ids);
			if *level == pulldown_cmark::HeadingLevel::H2 {
				sections.push((id.clone(), name));
			}
			out.push(Event::Start(Tag::Heading { level: *level, id: Some(CowStr::from(id)), classes: classes.clone(), attrs: attrs.clone() }));
			k += 1;
			continue;
		}
		out.push(events[k].clone());
		k += 1;
	}
	let mut body = String::new();
	html::push_html(&mut body, out.into_iter());
	(body, sections)
}

/// (html body, [(id, title)] of its sections, search entries) of one page.
fn render(path: &str, text: &str, depth: usize, title: &str) -> (String, Vec<(String, String)>, Vec<Json>) {
	let fence = Regex::new(r"(?ms)^```([^\n]*)\n(.*?)^```\s*$").unwrap();
	let mut blocks: Vec<(String, String)> = Vec::new();
	let text = fence.replace_all(text, |m: &regex::Captures| {
		let (lang, code) = (m[1].trim(), &m[2]);
		let key = format!("CODEBLOCK{}X", blocks.len());
		let block = if lang.starts_with("parts") {
			let body = highlight(code.trim_end_matches('\n'));
			let mut button = String::new();
			if runnable(code) {
				button = format!("<a class=\"try\" href=\"{}play.html#code={}\" title=\"open this in the playground\">try it</a>", "../".repeat(depth + 1), base64url(code.as_bytes()));
			}
			format!("<div class=\"code parts\">{button}<pre>{body}</pre></div>")
		} else {
			format!("<div class=\"code\"><pre>{}</pre></div>", escape(code.trim_end_matches('\n')))
		};
		blocks.push((key.clone(), block));
		format!("\n\n{key}\n\n")
	});
	let (mut body, sections) = markdown(&text);
	for (key, value) in &blocks {
		body = body.replace(&format!("<p>{key}</p>"), value);
	}
	let code = Regex::new(r"<code>(.*?)</code>").unwrap();
	body = code.replace_all(&body, |m: &regex::Captures| format!("<code>{}</code>", m[1].replace("\\|", "|"))).into_owned();
	// Links between pages: .md in the sources, .html on the site.
	let link = Regex::new(r##"href="([^"#:]+)\.md(#[^"]*)?""##).unwrap();
	body = link.replace_all(&body, |m: &regex::Captures| format!("href=\"{}.html{}\"", &m[1], m.get(2).map_or("", |g| g.as_str()))).into_owned();
	let heading = Regex::new(r#"<h2 id="([^"]+)">(.*?)</h2>"#).unwrap();
	let noise = Regex::new(r#"<a class="try"[^>]*>.*?</a>|</?span[^>]*>"#).unwrap();
	let tag = Regex::new(r"<[^>]+>").unwrap();
	let space = Regex::new(r"\s+").unwrap();
	let mut cuts: Vec<usize> = body.match_indices("<h2 ").map(|(at, _)| at).collect();
	cuts.insert(0, 0);
	cuts.push(body.len());
	let mut entries = Vec::new();
	for pair in cuts.windows(2) {
		let part = &body[pair[0]..pair[1]];
		if pair[0] == pair[1] && pair[1] != 0 {
			continue;
		}
		let found = heading.captures(part);
		let part = noise.replace_all(part, "");
		let plain = unescape(&tag.replace_all(&part, " "));
		let text: String = space.replace_all(&plain, " ").chars().take(1200).collect();
		let mut entry = Json::dict();
		entry
			.set("page", path.replace(".md", ".html"))
			.set("anchor", found.as_ref().map_or(String::new(), |h| h[1].to_string()))
			.set("title", title)
			.set("section", found.as_ref().map_or(String::new(), |h| unescape(&tag.replace_all(&h[2], ""))))
			.set("text", text);
		entries.push(entry);
	}
	(body, sections, entries)
}

