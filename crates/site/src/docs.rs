/// The template with each {name} replaced (only in the template, never inside what goes in).
fn fill(template: &str, values: &[(&str, &str)]) -> String {
	let mut out = String::new();
	let mut rest = template;
	while let Some(at) = rest.find('{') {
		out.push_str(&rest[..at]);
		let close = rest[at..].find('}').map(|c| at + c);
		match close.and_then(|c| values.iter().find(|(k, _)| *k == &rest[at + 1..c]).map(|(_, v)| (c, v))) {
			Some((c, v)) => {
				out.push_str(v);
				rest = &rest[c + 1..];
			}
			None => {
				out.push('{');
				rest = &rest[at + 1..];
			}
		}
	}
	out.push_str(rest);
	out
}

fn nav_html(current: &str, up: &str) -> String {
	let mut out = String::new();
	for (group, pages) in NAV {
		out.push_str(&format!("<h4>{group}</h4><ul>"));
		for (path, title) in pages {
			let on = if *path == current { " class=\"on\"" } else { "" };
			out.push_str(&format!("<li><a{on} href=\"{up}{}\">{title}</a></li>", path.replace(".md", ".html")));
		}
		out.push_str("</ul>");
	}
	out
}

fn io<T>(result: std::io::Result<T>, path: &Path) -> Result<T, String> {
	result.map_err(|e| format!("{}: {e}", path.display()))
}

/// The generated pages that differ from what is in docs/.
pub fn stale() -> Vec<(&'static str, String)> {
	let docs = root().join("docs");
	generated().into_iter().filter(|(path, fresh)| std::fs::read_to_string(docs.join(path)).ok().as_deref() != Some(fresh.as_str())).collect()
}

/// Pages in NAV with no source.
pub fn missing() -> Vec<&'static str> {
	let docs = root().join("docs");
	NAV.iter().flat_map(|(_, pages)| pages.iter().map(|(p, _)| *p)).filter(|p| !docs.join(p).exists()).collect()
}

pub fn build(check_only: bool) -> Result<(), String> {
	let docs = root().join("docs");
	let out_dir = root().join("site/docs");
	let stale = stale();
	if check_only {
		if !stale.is_empty() {
			return Err(format!("out of date (run cargo run -p site -- docs): {}", stale.iter().map(|(p, _)| *p).collect::<Vec<_>>().join(", ")));
		}
		println!("generated reference pages are current");
		return Ok(());
	}
	for (path, fresh) in &stale {
		let target = docs.join(path);
		io(std::fs::create_dir_all(target.parent().unwrap()), &target)?;
		io(std::fs::write(&target, fresh), &target)?;
	}
	let missing = missing();
	if !missing.is_empty() {
		return Err(format!("pages in NAV with no source: {}", missing.join(", ")));
	}
	let order: Vec<(&str, &str)> = NAV.iter().flat_map(|(_, pages)| pages.iter().copied()).collect();
	let mut index = Vec::new();
	for (k, (path, title)) in order.iter().enumerate() {
		let depth = path.matches('/').count();
		let up = "../".repeat(depth);
		let source = docs.join(path);
		let (body, sections, entries) = render(path, &io(std::fs::read_to_string(&source), &source)?, depth, title);
		index.extend(entries);
		let toc = if sections.is_empty() {
			String::new()
		} else {
			format!("<h4>On this page</h4><ul>{}</ul>", sections.iter().map(|(i, t)| format!("<li><a href=\"#{i}\">{}</a></li>", escape(t))).collect::<String>())
		};
		let mut pager = String::new();
		if k > 0 {
			let (p, t) = order[k - 1];
			pager += &format!("<a class=\"prev\" href=\"{up}{}\">&larr; {t}</a>", p.replace(".md", ".html"));
		}
		if k + 1 < order.len() {
			let (p, t) = order[k + 1];
			pager += &format!("<a class=\"next\" href=\"{up}{}\">{t} &rarr;</a>", p.replace(".md", ".html"));
		}
		let page = fill(TEMPLATE, &[("title", &escape(title)), ("up", &up), ("nav", &nav_html(path, &up)), ("body", &body), ("toc", &toc), ("pager", &pager)]);
		let target = out_dir.join(path.replace(".md", ".html"));
		io(std::fs::create_dir_all(target.parent().unwrap()), &target)?;
		io(std::fs::write(&target, page), &target)?;
	}
	for asset in ["docs.css", "search.js"] {
		let from = root().join("site/docs-assets").join(asset);
		io(std::fs::copy(&from, out_dir.join(asset)), &from)?;
	}
	let images = docs.join("img");
	if images.exists() {
		io(std::fs::create_dir_all(out_dir.join("img")), &images)?;
		for image in io(std::fs::read_dir(&images), &images)? {
			let image = image.map_err(|e| e.to_string())?.path();
			io(std::fs::copy(&image, out_dir.join("img").join(image.file_name().unwrap())), &image)?;
		}
	}
	let search = out_dir.join("search.json");
	io(std::fs::write(&search, Json::List(index).dumps(false)), &search)?;
	home()?;
	let refreshed = if stale.is_empty() { String::new() } else { format!(" (refreshed {})", stale.iter().map(|(p, _)| *p).collect::<Vec<_>>().join(", ")) };
	println!("{} pages -> {}{refreshed}", order.len(), out_dir.display());
	Ok(())
}

/// site/index.html, the home page, from its template: the writer's desk source highlighted in.
fn home() -> Result<(), String> {
	let path = root().join("examples/layout.parts");
	let source = io(std::fs::read_to_string(&path), &path)?;
	let start = source.find("prop writers_desk").ok_or("examples/layout.parts has no writers_desk")?;
	let lines = partscript::lang::splitlines(&source[start..]);
	let end = (1..lines.len()).find(|&k| lines[k].chars().next().is_some_and(|c| !c.is_whitespace())).unwrap_or(lines.len());
	let desk = lines[..end].join("\n");
	let code = format!("<div class=\"code parts\"><pre>{}</pre></div>", highlight(desk.trim_end()));
	let template = root().join("site/docs-assets/home.html");
	let page = io(std::fs::read_to_string(&template), &template)?.replace("{desk_code}", &code);
	let target = root().join("site/index.html");
	io(std::fs::write(&target, page), &target)
}

#[cfg(test)]
mod tests {
	use super::*;

	#[test]
	fn base64_matches_python() {
		assert_eq!(base64url(b"prop a"), "cHJvcCBh");
		assert_eq!(base64url(b"prop ab"), "cHJvcCBhYg");
		assert_eq!(base64url(b"\xff\xfe"), "__4");
	}

	#[test]
	fn slugs_match_python_markdown() {
		assert_eq!(slugify("Materials: kitlib.geom.Mat"), "materials-kitlibgeommat");
		assert_eq!(slugify("check()"), "check");
		assert_eq!(slugify("cylinder, cone"), "cylinder-cone");
		let mut ids = HashSet::new();
		assert_eq!(unique("a".into(), &mut ids), "a");
		assert_eq!(unique("a".into(), &mut ids), "a_1");
		assert_eq!(unique("a".into(), &mut ids), "a_2");
	}

	#[test]
	fn generated_pages_are_current() {
		assert!(stale().is_empty(), "out of date (run cargo run -p site -- docs): {:?}", stale().iter().map(|(p, _)| *p).collect::<Vec<_>>());
	}

	#[test]
	fn every_page_is_in_the_nav() {
		assert!(missing().is_empty(), "pages in NAV with no source: {:?}", missing());
		let listed: HashSet<&str> = NAV.iter().flat_map(|(_, pages)| pages.iter().map(|(p, _)| *p)).collect();
		let docs = root().join("docs");
		let mut on_disk = Vec::new();
		let mut todo = vec![docs.clone()];
		while let Some(dir) = todo.pop() {
			for entry in std::fs::read_dir(dir).unwrap() {
				let path = entry.unwrap().path();
				if path.is_dir() {
					todo.push(path);
				} else if path.extension().is_some_and(|e| e == "md") {
					on_disk.push(path.strip_prefix(&docs).unwrap().to_string_lossy().to_string());
				}
			}
		}
		let unlisted: Vec<&String> = on_disk.iter().filter(|p| !listed.contains(p.as_str())).collect();
		assert!(unlisted.is_empty(), "pages missing from NAV: {unlisted:?}");
	}
}
