/// html.escape: & < > " and ' as entities.
pub fn escape(text: &str) -> String {
	let mut out = String::with_capacity(text.len());
	for c in text.chars() {
		match c {
			'&' => out.push_str("&amp;"),
			'<' => out.push_str("&lt;"),
			'>' => out.push_str("&gt;"),
			'"' => out.push_str("&quot;"),
			'\'' => out.push_str("&#x27;"),
			c => out.push(c),
		}
	}
	out
}

/// html.unescape, for the entities the docs produce.
fn unescape(text: &str) -> String {
	let mut out = String::with_capacity(text.len());
	let mut rest = text;
	while let Some(at) = rest.find('&') {
		out.push_str(&rest[..at]);
		rest = &rest[at..];
		let end = rest[1..].find(|c: char| !(c.is_ascii_alphanumeric() || c == '#')).map(|e| e + 1).unwrap_or(rest.len());
		let name = &rest[1..end];
		let decoded = match name {
			"amp" => Some('&'),
			"lt" => Some('<'),
			"gt" => Some('>'),
			"quot" => Some('"'),
			"apos" => Some('\''),
			"nbsp" => Some('\u{a0}'),
			"rarr" => Some('\u{2192}'),
			"larr" => Some('\u{2190}'),
			"middot" => Some('\u{b7}'),
			"mdash" => Some('\u{2014}'),
			"times" => Some('\u{d7}'),
			_ if name.starts_with("#x") => u32::from_str_radix(&name[2..], 16).ok().and_then(char::from_u32),
			_ if name.starts_with('#') => name[1..].parse().ok().and_then(char::from_u32),
			_ => None,
		};
		match decoded {
			Some(c) => {
				out.push(c);
				rest = if rest[end..].starts_with(';') { &rest[end + 1..] } else { &rest[end..] };
			}
			None => {
				out.push('&');
				rest = &rest[1..];
			}
		}
	}
	out.push_str(rest);
	out
}

fn is_word(c: char) -> bool {
	c.is_alphanumeric() || c == '_'
}

fn is_name_start(c: char) -> bool {
	c.is_ascii_lowercase() || c == '_'
}

/// The end of the token at chars[i..] and its kind: comment, string, colour, option, number, word or other
/// (the order a regex alternation tries them in).
fn token(chars: &[char], i: usize) -> (usize, &'static str) {
	let c = chars[i];
	let prev = if i > 0 { Some(chars[i - 1]) } else { None };
	let next = chars.get(i + 1).copied();
	if c == '#' && prev.map_or(true, char::is_whitespace) && next.is_some_and(char::is_whitespace) {
		return (chars.len(), "comment");
	}
	if c == '"' {
		if let Some(close) = chars[i + 1..].iter().position(|&q| q == '"') {
			return (i + close + 2, "string");
		}
	}
	if c == '#' && chars.len() >= i + 7 && chars[i + 1..i + 7].iter().all(char::is_ascii_hexdigit) {
		let mut end = i + 7;
		if chars.get(end) == Some(&'/') && chars.get(end + 1).is_some_and(|&w| is_word(w)) {
			end += 1;
			while chars.get(end).is_some_and(|&w| is_word(w)) {
				end += 1;
			}
		}
		return (end, "colour");
	}
	let boundary = prev.map_or(true, |p| !is_word(p));
	let word_end = || {
		let mut end = i + 1;
		while chars.get(end).is_some_and(|&w| is_word(w)) {
			end += 1;
		}
		end
	};
	if boundary && is_name_start(c) && chars.get(word_end()) == Some(&'=') {
		return (word_end(), "option");
	}
	if prev.map_or(true, |p| !is_word(p) && p != '.') {
		let mut at = i;
		if chars[at] == '-' {
			at += 1;
		}
		if chars.get(at) == Some(&'.') && chars.get(at + 1).is_some_and(char::is_ascii_digit) {
			at += 1;
		}
		if chars.get(at).is_some_and(char::is_ascii_digit) {
			at += 1;
			while chars.get(at).is_some_and(|&d| d.is_ascii_digit() || d == '.') {
				at += 1;
			}
			return (at, "number");
		}
	}
	if boundary && is_name_start(c) {
		return (word_end(), "word");
	}
	(i + 1, "other")
}

pub fn highlight(code: &str) -> String {
	let named = Regex::new(r"^(\s*)([a-z_]\w*)( = )").unwrap();
	let mut out = Vec::new();
	for full in code.split('\n') {
		let mut line = full;
		let mut pieces = String::new();
		if let Some(m) = named.captures(line) {
			pieces.push_str(&format!("{}<span class=\"v\">{}</span>{}", escape(&m[1]), &m[2], &m[3]));
			line = &line[m.get(0).unwrap().end()..];
		}
		let chars: Vec<char> = line.chars().collect();
		let mut first = true;
		let mut i = 0;
		while i < chars.len() {
			let (end, kind) = token(&chars, i);
			let text: String = chars[i..end].iter().collect();
			match kind {
				"word" if first && KEYWORDS.contains(&text.as_str()) => pieces.push_str(&format!("<span class=\"k\">{text}</span>")),
				"word" if WORDS.contains(&text.as_str()) => pieces.push_str(&format!("<span class=\"w\">{text}</span>")),
				"comment" => pieces.push_str(&format!("<span class=\"c\">{}</span>", escape(&text))),
				"string" => pieces.push_str(&format!("<span class=\"s\">{}</span>", escape(&text))),
				"colour" => pieces.push_str(&format!("<span class=\"swatch\" style=\"background:{}\"></span><span class=\"s\">{}</span>", &text[..7], escape(&text))),
				"option" => pieces.push_str(&format!("<span class=\"o\">{text}</span>")),
				"number" => pieces.push_str(&format!("<span class=\"n\">{text}</span>")),
				_ => pieces.push_str(&escape(&text)),
			}
			if !text.chars().all(char::is_whitespace) {
				first = false;
			}
			i = end;
		}
		out.push(pieces);
	}
	out.join("\n")
}

fn runnable(code: &str) -> bool {
	code.split('\n').any(|l| l.starts_with("prop ") || l.starts_with("building "))
}

/// base64.urlsafe_b64encode without its = padding.
fn base64url(bytes: &[u8]) -> String {
	const ALPHABET: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_";
	let mut out = String::new();
	for chunk in bytes.chunks(3) {
		let n = chunk.iter().enumerate().fold(0u32, |n, (k, &b)| n | (b as u32) << (16 - 8 * k));
		for k in 0..=chunk.len() {
			out.push(ALPHABET[(n >> (18 - 6 * k) & 63) as usize] as char);
		}
	}
	out
}

