def nav_html(current: str, up: str) -> str:
	out = []
	for group, pages in NAV:
		out.append(f"<h4>{group}</h4><ul>")
		for path, title in pages:
			on = ' class="on"' if path == current else ""
			out.append(f'<li><a{on} href="{up}{path.replace(".md", ".html")}">{title}</a></li>')
		out.append("</ul>")
	return "".join(out)


def build(check_only: bool = False) -> None:
	stale = []
	for path, make in GENERATED.items():
		target = DOCS / path
		fresh = make()
		if not target.exists() or target.read_text() != fresh:
			stale.append(path)
			if not check_only:
				target.parent.mkdir(parents=True, exist_ok=True)
				target.write_text(fresh)
	if check_only:
		if stale:
			sys.exit(f"out of date (run uv run python site/docs.py): {', '.join(stale)}")
		print("generated reference pages are current")
		return
	order = [path for _, pages in NAV for path, _ in pages]
	missing = [p for p in order if not (DOCS / p).exists()]
	if missing:
		sys.exit(f"pages in NAV with no source: {', '.join(missing)}")
	OUT.mkdir(parents=True, exist_ok=True)
	index = []
	titles = {path: title for _, pages in NAV for path, title in pages}
	for k, path in enumerate(order):
		depth = path.count("/")
		up = "../" * depth
		body, sections, entries = render(path, (DOCS / path).read_text(), depth, titles[path])
		index += entries
		toc = "<h4>On this page</h4><ul>" + "".join(f'<li><a href="#{i}">{html.escape(t)}</a></li>' for i, t in sections) + "</ul>" if sections else ""
		pager = ""
		if k > 0:
			pager += f'<a class="prev" href="{up}{order[k - 1].replace(".md", ".html")}">&larr; {titles[order[k - 1]]}</a>'
		if k + 1 < len(order):
			pager += f'<a class="next" href="{up}{order[k + 1].replace(".md", ".html")}">{titles[order[k + 1]]} &rarr;</a>'
		page = TEMPLATE.format(title=html.escape(titles[path]), up=up, nav=nav_html(path, up), body=body, toc=toc, pager=pager)
		target = OUT / path.replace(".md", ".html")
		target.parent.mkdir(parents=True, exist_ok=True)
		target.write_text(page)
	for asset in ("docs.css", "search.js"):
		(OUT / asset).write_text((ROOT / "site" / "docs-assets" / asset).read_text())
	images = DOCS / "img"
	if images.exists():
		(OUT / "img").mkdir(exist_ok=True)
		for image in images.iterdir():
			(OUT / "img" / image.name).write_bytes(image.read_bytes())
	(OUT / "search.json").write_text(json.dumps(index))
	home()
	print(f"{len(order)} pages -> {OUT}" + (f" (refreshed {', '.join(stale)})" if stale else ""))


def home() -> None:
	"""site/index.html, the home page, from its template: the writer's desk source highlighted in."""
	source = (ROOT / "examples" / "layout.parts").read_text()
	lines = source[source.index("prop writers_desk"):].splitlines()
	end = next((k for k, line in enumerate(lines[1:], 1) if line and not line[0].isspace()), len(lines))
	desk = "\n".join(lines[:end]).rstrip()
	code = f'<div class="code parts"><pre>{highlight(desk)}</pre></div>'
	(ROOT / "site" / "index.html").write_text((ROOT / "site" / "docs-assets" / "home.html").read_text().replace("{desk_code}", code))


if __name__ == "__main__":
	build(check_only="--check" in sys.argv)
