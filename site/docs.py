# ------------------------------------------------------------------ generated reference pages
def std_parts_page() -> str:
	"""docs/reference/std-parts.md from std.parts: every std part, what its comment says, its parameters."""
	from partscript.project import STD
	text = STD.read_text()
	lines = text.splitlines()
	out = ["# Standard parts", "", "<!-- generated by site/docs.py from src/partscript/std.parts: edit those comments, not this page -->", "",
		"Every project can `use` these: building blocks with their origin at the floor centre and their front toward -Y, "
		"like a prop. Their materials are parameters (pass `none` to leave a piece out).", ""]
	k = 0
	while k < len(lines):
		line = lines[k]
		if line.startswith("def "):
			comment = []
			j = k - 1
			while j >= 0 and lines[j].startswith("#"):
				comment.insert(0, lines[j].lstrip("# ").rstrip())
				j -= 1
			header = line
			while header.rstrip().endswith("\\"):
				k += 1
				header = header.rstrip()[:-1] + " " + lines[k].strip()
			words = header.split()
			name, params = words[1], [w for w in words[2:] if "=" in w]
			out += [f"## {name}", "", " ".join(comment), "", "| parameter | default |", "|---|---|"]
			out += [f"| `{p.split('=', 1)[0]}` | `{p.split('=', 1)[1]}` |" for p in params] or ["| (none) | |"]
			out += ["", "```parts", f'prop std_{name}_demo "{name}"', f"  use {name}", "```", ""]
		k += 1
	return "\n".join(out)


def materials_page() -> str:
	"""docs/reference/materials.md from the default host's material library."""
	from partscript import Host
	from partscript.lang import FINISHES
	from partscript.textures import _LIBRARY
	host = Host()
	out = ["# Material library", "", "<!-- generated by site/docs.py from the default host (partscript.textures): do not edit -->", "",
		"Every project can name these by key (`mat=steel_dark`). A host can add its own; `partscript list` shows what yours knows.", "",
		"| key | finish | colour | notes |", "|---|---|---|---|"]
	for key in sorted(host.materials):
		finish, colour, opts = _LIBRARY[key]
		mat = host.materials[key]
		notes = []
		if mat.emission or mat.emission_strength > 0:
			notes.append("lit (full bright)")
		if mat.alpha < 1:
			notes.append(f"see-through ({mat.alpha:g})")
		out.append(f'| `{key}` | {finish} | <span class="swatch" style="background:#{colour}"></span> `#{colour}` | {", ".join(notes)} |')
	out += ["", "## Finishes", "", "Any colour is a material: `#rrggbb/finish`, where the finish is one of "
		+ ", ".join(f"`{f}`" for f in FINISHES) + " (paint when left off). `glow` is lit and full bright; `glass` is see-through.", ""]
	return "\n".join(out)


GENERATED = {"reference/std-parts.md": std_parts_page, "reference/materials.md": materials_page}


# ------------------------------------------------------------------ highlighting
_TOKEN = re.compile(r'(?P<comment>(?:^|(?<=\s))#\s.*$)|(?P<string>"[^"]*")|(?P<colour>#[0-9a-fA-F]{6}(?:/\w+)?)|(?P<option>\b[a-z_]\w*(?==))'
	r"|(?P<number>(?<![\w.])-?\.?\d[\d.]*)|(?P<word>\b[a-z_]\w*\b)|(?P<other>.)", re.M)


def highlight(code: str) -> str:
	out = []
	for line in code.split("\n"):
		first = True
		named = re.match(r"^(\s*)([a-z_]\w*)( = )", line)
		pieces = []
		if named:
			pieces.append(html.escape(named.group(1)) + f'<span class="v">{named.group(2)}</span>{named.group(3)}')
			line = line[named.end():]
		for m in _TOKEN.finditer(line):
			kind, text = m.lastgroup, m.group()
			if kind == "word" and first and text in KEYWORDS:
				pieces.append(f'<span class="k">{text}</span>')
			elif kind == "word" and text in WORDS:
				pieces.append(f'<span class="w">{text}</span>')
			elif kind == "comment":
				pieces.append(f'<span class="c">{html.escape(text)}</span>')
			elif kind == "string":
				pieces.append(f'<span class="s">{html.escape(text)}</span>')
			elif kind == "colour":
				pieces.append(f'<span class="swatch" style="background:{text[:7]}"></span><span class="s">{html.escape(text)}</span>')
			elif kind == "option":
				pieces.append(f'<span class="o">{text}</span>')
			elif kind == "number":
				pieces.append(f'<span class="n">{text}</span>')
			else:
				pieces.append(html.escape(text))
			if not text.isspace():
				first = False
		out.append("".join(pieces))
	return "\n".join(out)


def runnable(code: str) -> bool:
	return bool(re.search(r"^(prop|building) ", code, re.M))


# ------------------------------------------------------------------ pages
def render(path: str, text: str, depth: int, title: str = "") -> tuple[str, list, list]:
	"""(html body, [(id, title)] of its sections, search entries) of one page."""
	blocks: dict = {}

	def stash(match) -> str:
		lang, code = match.group(1).strip(), match.group(2)
		key = f"CODEBLOCK{len(blocks)}X"
		if lang.startswith("parts"):
			body = highlight(code.rstrip("\n"))
			button = ""
			if runnable(code):
				encoded = base64.urlsafe_b64encode(code.encode()).decode().rstrip("=")
				button = f'<a class="try" href="{"../" * (depth + 1)}play.html#code={encoded}" title="open this in the playground">try it</a>'
			blocks[key] = f'<div class="code parts">{button}<pre>{body}</pre></div>'
		else:
			blocks[key] = f'<div class="code"><pre>{html.escape(code.rstrip(chr(10)))}</pre></div>'
		return f"\n\n{key}\n\n"

	text = re.sub(r"^```([^\n]*)\n(.*?)^```\s*$", stash, text, flags=re.S | re.M)
	md = markdown.Markdown(extensions=["tables", "toc", "attr_list"], extension_configs={"toc": {"toc_depth": "2-3"}})
	body = md.convert(text)
	for key, value in blocks.items():
		body = body.replace(f"<p>{key}</p>", value)
	body = re.sub(r"<code>(.*?)</code>", lambda m: "<code>" + m.group(1).replace("\\|", "|") + "</code>", body)  # a | escaped for a table
	# Links between pages: .md in the sources, .html on the site.
	body = re.sub(r'href="([^"#:]+)\.md(#[^"]*)?"', lambda m: f'href="{m.group(1)}.html{m.group(2) or ""}"', body)
	sections = [(t["id"], t["name"]) for t in _flat(md.toc_tokens) if t["level"] == 2]
	entries = []
	title = title or path
	for part in re.split(r"(?=<h2 )", body):
		heading = re.search(r'<h2 id="([^"]+)">(.*?)</h2>', part)
		part = re.sub(r'<a class="try"[^>]*>.*?</a>|</?span[^>]*>', "", part)
		plain = html.unescape(re.sub(r"<[^>]+>", " ", part))
		entries.append({"page": path.replace(".md", ".html"), "anchor": heading.group(1) if heading else "",
			"title": title, "section": html.unescape(re.sub(r"<[^>]+>", "", heading.group(2))) if heading else "",
			"text": re.sub(r"\s+", " ", plain)[:1200]})
	return body, sections, entries


def _flat(tokens: list) -> list:
	out = []
	for token in tokens:
		out.append(token)
		out += _flat(token.get("children", []))
	return out


